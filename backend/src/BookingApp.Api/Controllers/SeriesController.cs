using BookingApp.Core.Bookings;
using BookingApp.Core.Payments;
using BookingApp.Core.Scheduling;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.RateLimiting;

namespace BookingApp.Api.Controllers;

/// <summary>Weekly series of the current customer: book, see, pay for and cancel them, date by date.</summary>
[AllowAnonymous]
[Route("api/series")]
public sealed class SeriesController(SeriesService series, DepositService deposits, VenueService venue, TimeProvider time) : ApiControllerBase
{
    /// <summary>Holds the same time every week ("every Tuesday 18:00 for 8 weeks"), date by date.</summary>
    /// <remarks>
    /// Each date is booked on its own, under the same rules as one booking: the answer lists every date as held, or
    /// failed with a code (slot_taken, resource_closed, too_far_ahead …), and one failed date does not stop the rest.
    /// Held dates are holds: confirm the series to pay the deposits. A series counts once toward the limit of upcoming
    /// bookings. Send an Idempotency-Key and a retry returns the first answer instead of booking again.
    /// </remarks>
    /// <param name="request">The first date and time, and how many weeks.</param>
    /// <param name="customer">Bound from the auth or customer cookie.</param>
    /// <param name="idempotencyKey">Optional. A key generated by the client once per series and reused on retries.</param>
    /// <param name="ct">Cancelled when the client goes away.</param>
    [HttpPost]
    [EnableRateLimiting(BookingsController.WritesPolicy)]
    [Idempotent]
    [EndpointName("CreateSeries")]
    [Consumes(Json)]
    [ProducesResponseType<SeriesResponse>(StatusCodes.Status200OK, Json)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJson, Description = "validation_failed")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJson, Description = "resource_not_found")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict, ProblemJson, Description = "request_in_progress")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status422UnprocessableEntity, ProblemJson, Description = "invalid_weeks, idempotency_key_reused")]
    [ProducesResponseType(StatusCodes.Status429TooManyRequests)]
    public async Task<ActionResult<SeriesResponse>> Create(CreateSeriesRequest request, CurrentCustomer customer,
        [FromHeader(Name = IdempotentAttribute.Header)] string? idempotencyKey, CancellationToken ct)
    {
        _ = idempotencyKey;   // handled by [Idempotent]
        var email = string.IsNullOrWhiteSpace(request.Email) ? customer.AccountEmail : request.Email;
        var result = await series.BookWeeklyAsync(customer.Id, request.Name!, email, request.ResourceId!, request.Start!.Value,
            request.Slots ?? 1, request.Weeks!.Value, ct);
        if (!result.IsSuccess) return Failure(result.Error!);

        var dates = result.Value!.Dates;
        var responses = await ResponsesAsync([.. dates.Where(d => d.Booking is not null).Select(d => d.Booking!)], ct);
        var catalog = await venue.CatalogAsync(ct);
        return new SeriesResponse(result.Value.SeriesId, dates.Count(d => d.Booking is not null), dates.Count(d => d.Booking is null),
            [.. dates.Select(d => new SeriesDateResponse(d.Index, d.LocalDate.ToString("yyyy-MM-dd"), d.Start,
                d.Booking is null ? SeriesDateOutcome.Failed : SeriesDateOutcome.Held,
                d.Booking is null ? null : responses[d.Booking.Id], d.Error?.Code, d.Error?.Message))]);
    }

    /// <summary>The bookings of one of the current customer's series, in date order.</summary>
    /// <param name="id">The series id.</param>
    [HttpGet("{id:guid}")]
    [EndpointName("GetSeries")]
    [ProducesResponseType<List<BookingResponse>>(StatusCodes.Status200OK, Json)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJson, Description = "series_not_found")]
    public async Task<ActionResult<List<BookingResponse>>> Get(Guid id, CurrentCustomer customer, CancellationToken ct)
    {
        var result = await series.GetAsync(customer.Id, id, ct);
        if (!result.IsSuccess) return Failure(result.Error!);
        var responses = await ResponsesAsync(result.Value!, ct);
        return result.Value!.Select(b => responses[b.Id]).ToList();
    }

    /// <summary>Pays the deposit for and confirms every date of the series that is still held, date by date.</summary>
    /// <remarks>Each date is charged and confirmed on its own; the answer says which succeeded (a declined card or an expired hold fails that date).</remarks>
    /// <param name="id">The series id.</param>
    /// <param name="request">The payment token, as for one booking.</param>
    [HttpPost("{id:guid}/confirm")]
    [EnableRateLimiting(BookingsController.WritesPolicy)]
    [EndpointName("ConfirmSeries")]
    [ProducesResponseType<SeriesChangesResponse>(StatusCodes.Status200OK, Json)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJson, Description = "validation_failed")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJson, Description = "series_not_found")]
    [ProducesResponseType(StatusCodes.Status429TooManyRequests)]
    public async Task<ActionResult<SeriesChangesResponse>> Confirm(Guid id, CurrentCustomer customer,
        [FromBody(EmptyBodyBehavior = Microsoft.AspNetCore.Mvc.ModelBinding.EmptyBodyBehavior.Allow)] ConfirmBookingRequest? request, CancellationToken ct) =>
        await ChangesAsync(await series.ConfirmAsync(customer.Id, id, request?.PaymentToken, ct), ct);

    /// <summary>Cancels every date of the series that is still on, refunding deposits as for one booking.</summary>
    /// <remarks>A date past the cancellation cut-off stays booked and is listed with too_late_to_cancel. To cancel one date, cancel that booking.</remarks>
    /// <param name="id">The series id.</param>
    [HttpPost("{id:guid}/cancel")]
    [EnableRateLimiting(BookingsController.WritesPolicy)]
    [EndpointName("CancelSeries")]
    [ProducesResponseType<SeriesChangesResponse>(StatusCodes.Status200OK, Json)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJson, Description = "series_not_found")]
    [ProducesResponseType(StatusCodes.Status429TooManyRequests)]
    public async Task<ActionResult<SeriesChangesResponse>> Cancel(Guid id, CurrentCustomer customer, CancellationToken ct) =>
        await ChangesAsync(await series.CancelAsync(customer.Id, id, ct), ct);

    private async Task<ActionResult<SeriesChangesResponse>> ChangesAsync(Core.Common.Result<IReadOnlyList<SeriesChange>> result, CancellationToken ct)
    {
        if (!result.IsSuccess) return Failure(result.Error!);
        var changes = result.Value!;
        var responses = await ResponsesAsync([.. changes.Select(c => c.Booking)], ct);
        return new SeriesChangesResponse(changes.Count(c => c.Error is null), changes.Count(c => c.Error is not null),
            [.. changes.Select(c => new SeriesChangeResponse(c.Booking.Id, c.Error is null, c.Error?.Code, c.Error?.Message, responses[c.Booking.Id]))]);
    }

    private async Task<Dictionary<Guid, BookingResponse>> ResponsesAsync(IReadOnlyList<Booking> list, CancellationToken ct)
    {
        var catalog = await venue.CatalogAsync(ct);
        var payments = await deposits.CurrentForAsync([.. list.Select(b => b.Id)], ct);
        var now = time.GetUtcNow();
        return list.ToDictionary(b => b.Id, b => BookingResponse.From(b, catalog, catalog.Policy, now, payments.GetValueOrDefault(b.Id), deposits.Deposit));
    }
}
